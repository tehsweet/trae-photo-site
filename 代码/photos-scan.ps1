# Regenerate photos-data.js from the photo folder.
# Run by "update-photos.bat"; safe to run again whenever photos are added.
param([switch]$NoOpen)

$ErrorActionPreference = 'Stop'

# Folder / page names are built from char codes so this file stays ASCII-only
# (Windows PowerShell 5.1 reads BOM-less files as ANSI, which would garble Chinese).
$photoName = -join ([char[]](0x7167, 0x7247))          # 照片
$pageName = $photoName + '.html'                        # 照片.html

$root = Split-Path -Parent $PSScriptRoot
$photoDir = Join-Path $root $photoName
$outFile = Join-Path $PSScriptRoot 'photos-data.js'

if (-not (Test-Path -LiteralPath $photoDir)) {
  Write-Host "[ERROR] Photo folder not found: $photoDir"
  exit 1
}

$exts = @('.jpg', '.jpeg', '.png', '.gif', '.webp', '.bmp')
$files = Get-ChildItem -LiteralPath $photoDir -File |
  Where-Object { $exts -contains $_.Extension.ToLower() } |
  Sort-Object LastWriteTime -Descending

$items = foreach ($f in $files) {
  '"' + ($f.Name -replace '\\', '\\' -replace '"', '\"') + '"'
}
$list = @($items) -join ','

$content = "/* Auto-generated by update-photos.bat - do not edit by hand. */`r`n" +
  "window.PHOTOS = [$list];`r`n"

[System.IO.File]::WriteAllText($outFile, $content, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "[OK] $(@($files).Count) photo(s) listed in photos-data.js"

if (-not $NoOpen) {
  $page = Join-Path $PSScriptRoot $pageName
  if (Test-Path -LiteralPath $page) {
    Start-Process -FilePath $page
  } else {
    Write-Host "[WARN] Page not found: $page"
  }
}
